"""Snake Duel · Arenas: an arena is a 24 × 20 board of walls with its own speed and number of foods."""
from ..level_common import LevelError
from . import Grid, Int

COLS, ROWS = 24, 20
START_FREE = {9: (2, 8), 10: (15, 21)}     # both snakes' starting cells and 3 cells ahead of each head
START = (5, 9)                              # player 2's head (player 1's is (18, 10))
MIN_FREE = 0.65


def _check(a):
    w = a["walls"]
    for row, (lo, hi) in START_FREE.items():
        if any(w[row][x] != "." for x in range(lo, hi + 1)):
            raise LevelError(f"row {row} columns {lo}-{hi} must be free (a snake starts there)")
    free = {(x, y) for y in range(ROWS) for x in range(COLS) if w[y][x] == "."}
    if len(free) < MIN_FREE * COLS * ROWS:
        raise LevelError(f"at least {int(MIN_FREE * 100)} % of the cells must be free ({len(free)} of {COLS * ROWS} are)")
    seen, stack = {START}, [START]
    while stack:
        x, y = stack.pop()
        for n in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if n in free and n not in seen:
                seen.add(n)
                stack.append(n)
    if len(seen) != len(free):
        raise LevelError("every free cell must be reachable (no closed-off pockets)")


def _walls(a):
    return sum(r.count("#") for r in a["walls"])


